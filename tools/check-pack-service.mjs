import assert from 'node:assert/strict';
import {createHandler, hash, randomToken, randomCode, safeEqual, normalizeCode, validCode} from '../supabase/functions/quizman/index.mjs';
const env={SUPABASE_URL:'https://example.supabase.co',SUPABASE_SERVICE_ROLE_KEY:'test-role',TELEGRAM_WEBHOOK_SECRET:'test-webhook',TELEGRAM_BOT_TOKEN:'test-bot'};
const calls=[];
const token=randomToken();
let mode='unlinked';
const fake=async(url,options={})=>{
 calls.push({url,options});
 if(url.includes('/rpc/qm_rate_limit'))return Response.json(true);
 if(url.includes('/qm_devices?'))return Response.json(mode==='unlinked'?[]:[{telegram_id:123}]);
 if(url.includes('/qm_entitlements?'))return Response.json(mode==='owned'?[{pack_id:'pack-ru'}]:[]);
 if(url.includes('/qm_packs?'))return Response.json([{id:'pack-ru',title:'Pack',language:'ru',question_count:750,topic_count:15,sha256:'a'.repeat(64),storage_path:'pack-ru.json',is_free:false}]);
 if(url.includes('/qm_device_links')&&options.method==='POST')return Response.json([JSON.parse(options.body)]);
 if(url.includes('/qm_device_links?'))return Response.json([{telegram_id:mode==='owned'?123:null,expires_at:new Date(Date.now()+60000).toISOString()}]);
 if(url.includes('/storage/'))return new Response('{"Questions":[]}');
 throw Error('Unexpected request');
};
const handler=createHandler(env,fake);
const request=(path,method='GET',headers={})=>new Request('https://example.supabase.co/functions/v1/quizman'+path,{method,headers});
assert.equal((await handler(request('/v1/packs?language=ru'))).status,401);
assert.equal((await handler(request('/telegram','POST'))).status,401);
assert.equal(calls.length,0,'Unauthorized callers must not touch DB');
assert.equal(safeEqual('a','b'),false);assert.equal(safeEqual('abc','abc'),true);
for(let i=0;i<100;i++){assert(validCode(randomCode()));assert.match(randomToken(),/^[a-f0-9]{64}$/);}
assert.equal(normalizeCode(' abcd-2345 '),'ABCD2345');
const pairing=await (await handler(request('/v1/device-links','POST'))).json();
assert(validCode(pairing.code));assert.match(pairing.pollToken,/^[a-f0-9]{64}$/);
const saved=JSON.parse(calls.at(-1).options.body);
assert.equal(saved.poll_hash,await hash(pairing.pollToken));assert(!JSON.stringify(saved).includes(pairing.pollToken));
assert.equal(saved.device_hash,await hash(await hash('device:'+pairing.pollToken)));
mode='linked';
const auth={Authorization:'Bearer '+token};
assert.equal((await handler(request('/v1/packs/pack-ru/download','GET',auth))).status,403);
assert.equal((await handler(request('/v1/packs?language=xx','GET',auth))).status,400);
assert.deepEqual((await (await handler(request('/v1/packs?language=ru','GET',auth))).json()).packs,[]);
mode='owned';
const packs=await (await handler(request('/v1/packs?language=ru','GET',auth))).json();
assert.equal(packs.packs[0].count,750);assert.equal(packs.packs[0].topics,15);
assert(!('storage_path' in packs.packs[0]));
const downloaded=await handler(request('/v1/packs/pack-ru/download','GET',auth));assert.equal(downloaded.status,200);assert.equal(await downloaded.text(),'{"Questions":[]}');
const approved=await (await handler(request('/v1/device-links/status','GET',{Authorization:'Bearer '+pairing.pollToken}))).json();
assert.equal(approved.deviceToken,await hash('device:'+pairing.pollToken));
console.log('Pack API checks passed: authentication, webhook secret, code/token generation, denied downloads, owned downloads, Android response contract.');
