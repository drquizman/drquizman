    fun lastStretch(): String = listOf(
        "Финишная прямая!",
        "Кто там на последнем месте? Галерка, догоняй!",
        "Ещё немного, ещё чуть-чуть!",
        "Иииии последний рывок!",
    ).random()

    fun questionFlavor(index: Int, total: Int): String? = when {
        total >= 3 && index == (total / 3).coerceAtLeast(1) -> afterFirstThird()
        total >= 3 && index == total - 2 -> lastStretch()
        else -> null
    }

    fun roundOver(): String = listOf(
        "Раунд завершён! Все молодцы! Посмотрим нашу турнирную таблицу",
        "Ну наконец-то можно подвести промежуточные итоги",
        "Вам интересно, кто у нас лидер после этого раунда? Мне — очень!",
        "Только мне показалось, что игроки начали засыпать в процессе игры?",
        "Можно сказать, отыграли на одном дыхании! Кто же отличился в этот раз?",
    ).random()

    fun standings(ranked: List<String>): String {
        if (ranked.isEmpty()) return roundOver()
        val bits = mutableListOf(roundOver())
        if (ranked.size >= 2) {
            bits += listOf(
                "На последнем месте у нас ${ranked.last()}.",
                "Вторую строчку снизу занимает ${ranked.last()}.",
            ).random()
        }
        val mid = ranked.drop(1).dropLast(1)
        if (mid.isNotEmpty() && ranked.size >= 4) {
            bits += "В середине турнирной таблицы у нас идут: ${mid.joinToString(", ")}."
        }
        if (ranked.size >= 3) {
            bits += "Второе место занимает ${ranked[1]}."
        }
        bits += listOf(
            "На первом месте — ${ranked.first()}",
            "Лидер нашей викторины — ${ranked.first()}",
            "В самом верху — ${ranked.first()}",
        ).random()
        return bits.joinToString(" ")
    }

