        "Не стесняйтесь, телефоны в руки — сегодня лечение интеллекта, очередь живая!",
    )

    fun lobbyChatter(count: Int, ready: Int, previous: String = ""): String {
        val extra = if (count > 0 && ready in 1 until count) {
            listOf("Готовы $ready из $count. Ждём остальных!")
        } else {
            emptyList()
        }
        val options = waitingPool + extra
        return options.filter { it != previous }.randomOrNull() ?: options.random()
    }

    fun playerJoined(name: String, first: Boolean): String {
        if (first) return "Итак, первым к нам на приём пришёл сегодня $name"
        return listOf(
            "Следующий игрок — $name",
            "Теперь приветствуем — $name",
            "$name, а ты не ошибся дверью? Ну ладно, посмотрим на тебя в действии.",
            "Ооооо, а тебя, $name, я вообще не ожидал тут увидеть!",
            "Привет, $name!",
            "$name, рад тебя видеть!",
            "$name, добро пожаловать!",
            "Не стесняйся, $name, присоединяйся!",
            "$name, мы сегодня уже виделись? Или я обознался?",
            "Мотай мой лысый череп, кого я вижу!? $name!",
            "Поприветствуем следующего игрока бурными аплодисментами! $name",
            "$name, надеюсь сегодня обойдётся без нервов...",
        ).random()
    }

    fun lobbyIdle(count: Int): String = lobbyWaiting(count, 0)

    fun lobbyWaiting(count: Int, ready: Int): String = when {
        count == 0 || ready == 0 -> waiting()
        ready < count -> "Готовы $ready из $count. Ждём остальных!"
        else -> matchStart()
    }

    fun matchStart(): String =
        "Итак, все в сборе, и мы готовы начать лечение... то есть сражение! Сражение, в котором все окажутся победителями, но лидер, конечно, будет только один! И мы узнаем его имя совсем скоро! А пока начинаем!"

    fun matchStartWithGrant(points: Int): String =
        "Стартового капитала сегодня нет — каждому сразу по $points баллов, чтобы было что терять. И начинаем!"

    fun intro(type: CompetitionType): String =
        MechanicCatalog[type]?.intro?.invoke() ?: "Продолжаем шоу!"

    fun chooseTopic(name: String, lastPlace: Boolean): String = if (lastPlace) {
        listOf(
            "Чтобы тебе не так обидно было быть на последнем месте, $name, выбирай тему ты.",
            "Кто отстаёт, тот и выбирает тему этого раунда. $name, это ты",
        ).random()
    } else {
        listOf(
            "Кому же мы доверим выбор темы в этом раунде!? $name, попробуй ты!",
            "Обычно выбор темы помогает добиться лучших результатов, посмотрим как получится у тебя, $name, выбирай тему",
        ).random()
    }

    fun topicPicked(topic: String): String =
        "Тема раунда — $topic! Поехали!"

    fun titles(type: CompetitionType): String =
        MechanicCatalog[type]?.title.orEmpty()

